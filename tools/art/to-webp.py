# Dev tool: PNG bake -> WebP in assets/art, plus js/art-data.js (anchors as fractions of the painting)
import sys, glob, json, os
from PIL import Image
src, dst, datajs = sys.argv[1:4]
os.makedirs(dst, exist_ok=True)
tot = 0
for p in sorted(glob.glob(src + '/*.png')):
    n = os.path.basename(p)[:-4]
    im = Image.open(p)
    q = 84 if n.endswith('sketch') else 80
    out = os.path.join(dst, n + '.webp')
    im.save(out, 'WEBP', quality=q, method=3)
    tot += os.path.getsize(out)
anch = {}
for p in glob.glob(src + '/anchors-*.json'):
    anch.update(json.load(open(p)))
sizes = {'d': [1440, 810], 'm': [560, 1040]}
with open(datajs, 'w') as f:
    f.write('/* GENERATED by tools/art/to-webp.py from the painted scenes. Do not edit by hand.\n   Anchors are [x, y, radius] as fractions of the painting width/height. */\n')
    f.write('const ART = ' + json.dumps({'size': sizes, 'anchors': anch}, separators=(',', ':')) + ';\n')
print('total KB', tot // 1024)
